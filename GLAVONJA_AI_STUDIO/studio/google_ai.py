# --------------------------------------------------------------------------- licence record (json mirror)
def record_google_asset(path: Path, kind: str, service: str, details: dict):
    data = read_json(ASSET_LICENSE_JSON, {"assets": []})
    data["assets"].append({"path": str(Path(path).resolve().relative_to(ROOT)) if str(path).startswith(str(ROOT)) else str(path),
                           "kind": kind, "service": service, "created": now_iso(),
                           "terms": "Generated by the user's own Google account; see Google Generative AI "
                                    "Additional Terms of Service. Keep for the channel's records.",
                           **details})
    atomic_write_json(ASSET_LICENSE_JSON, data)
    record_license(path, kind, service, "Google generative AI output (user account)", json.dumps(details)[:500])


# --------------------------------------------------------------------------- pricing / estimates
def pricing() -> dict:
    return read_json(CONFIG_DIR / "google_pricing.json", {})


def estimate_tts(texts: list[str]) -> dict:
    p = pricing().get("gemini_tts", {})
    chars = sum(len(t) for t in texts)
    words = sum(len(t.split()) for t in texts)
    audio_sec = words / max(1e-6, p.get("words_per_second", 2.6))
    in_tok = chars / 4
    out_tok = audio_sec * p.get("audio_tokens_per_second", 25)
    usd = in_tok / 1e6 * p.get("usd_per_1m_input_tokens", 0) + out_tok / 1e6 * p.get("usd_per_1m_audio_output_tokens", 0)
    return {"service": "Gemini TTS", "requests": len(texts), "characters": chars,
            "audio_seconds_est": round(audio_sec, 1), "output_tokens_est": int(out_tok),
            "free_tier_requests_per_day": p.get("free_tier_requests_per_day"),
            "fits_free_tier": (p.get("free_tier_requests_per_day") or 0) >= len(texts),
            "usd_if_paid_est": round(usd, 4), "pricing_verified": p.get("last_verified", "UNVERIFIED"),
            "note": "Estimate only. Check https://ai.google.dev/gemini-api/docs/pricing and your AI Studio quota."}


def estimate_flow(n_clips: int, mode: str | None = None) -> dict:
    p = pricing().get("flow", {})
    mode = mode or p.get("default_mode", "fast")
    per = p.get("credits_per_clip", {}).get(mode)
    return {"service": "Google Flow", "clips": n_clips, "mode": mode, "credits_per_clip_est": per,
            "credits_total_est": per * n_clips if isinstance(per, (int, float)) else None,
            "pricing_verified": p.get("last_verified", "UNVERIFIED"),
            "note": "Flow credit costs depend on your plan/model; check the credit counter in Flow before generating."}


# --------------------------------------------------------------------------- Gemini TTS
def gemini_key(settings=None) -> str:
    return (settings or load_settings()).get("google", {}).get("api_key", "").strip()


def gemini_available(settings=None) -> bool:
    s = settings or load_settings()
    g = s.get("google", {})
    return bool(g.get("enabled") and gemini_key(s))


def gemini_tts(text: str, out_wav: Path, settings=None, voice: str | None = None, style_hint: str | None = None) -> Path:
    s = settings or load_settings()
    g = s["google"]
    key = gemini_key(s)
    if not key:
        raise RuntimeError("No Gemini API key in settings (google.api_key)")
    voice = voice or g.get("tts_voice") or "Charon"
    hint = style_hint or g.get("tts_style_prompt", "")
    body = {"contents": [{"parts": [{"text": (hint + "\n" if hint else "") + text}]}],
            "generationConfig": {"responseModalities": ["AUDIO"],
                                 "speechConfig": {"voiceConfig": {"prebuiltVoiceConfig": {"voiceName": voice}}}}}
    req = urllib.request.Request(GEMINI_URL.format(model=g.get("tts_model", "gemini-2.5-flash-preview-tts")),
                                 data=json.dumps(body).encode(), method="POST",
                                 headers={"Content-Type": "application/json", "x-goog-api-key": key})
    with urllib.request.urlopen(req, timeout=180) as r:
        resp = json.loads(r.read())
    try:
        part = resp["candidates"][0]["content"]["parts"][0]["inlineData"]
    except (KeyError, IndexError):
        raise RuntimeError(f"Gemini TTS returned no audio: {str(resp)[:300]}")
    pcm = base64.b64decode(part["data"])
    rate = 24000
    mt = part.get("mimeType", "")
    if "rate=" in mt:
        try:
            rate = int(mt.split("rate=")[1].split(";")[0])
        except ValueError:
            pass
    with wave.open(str(out_wav), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(pcm)
    record_google_asset(out_wav, "voice", "Gemini TTS", {"voice": voice, "model": g.get("tts_model"), "chars": len(text)})
    return out_wav


class GeminiEngine:
    """Plugs into audio.pick_engine()."""
    name = "gemini"

    def synth(self, text, out: Path, lang, settings):
        gemini_tts(text, out, settings)


def audition_voices(sample_text: str, voices: list[str], out_dir: Path, settings=None) -> list[dict]:
    """Generate the same line in several voices so the user can pick and LOCK one."""
    out_dir.mkdir(parents=True, exist_ok=True)
    res = []
    for v in voices:
        p = out_dir / f"gemini_{v}.wav"
        try:
            if not p.exists():
                gemini_tts(sample_text, p, settings, voice=v)
            res.append({"voice": v, "file": str(p), "ok": True})
        except Exception as e:
            res.append({"voice": v, "ok": False, "error": str(e)[:200]})
    return res


# --------------------------------------------------------------------------- Flow bridge
FLOW_PROMPT = """{shot}

STYLE (must match the GLAVONJA YouTube channel exactly - see attached reference images):
{style}

CHARACTER: the SAME stickman as in the attached character sheet. Do NOT redesign him: same head size,
same line thickness, same face, same colours, same clothing.  2D flat cartoon, thick clean outlines,
no 3D, no realistic textures, no text in the image.
Camera: {camera}.  Duration: {dur:.1f} s.  16:9.
"""


def flow_requests(project, scenes: list[dict], style: dict) -> Path:
    """Write ready-to-paste Flow prompts + reference images for the scenes flagged use_flow."""
    folder = project.path("flow")
    (folder / "inbox").mkdir(parents=True, exist_ok=True)
    refs = folder / "references"
    refs.mkdir(exist_ok=True)
    for src in (ROOT / "assets" / "characters").glob("character_sheet*.png"):
        shutil.copy2(src, refs / src.name)
    for src in sorted((ROOT / "references" / "frames").glob("*.*"))[:6]:
        if src.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp"):
            shutil.copy2(src, refs / src.name)
    style_txt = "; ".join(f"{k}: {v}" for k, v in (style.get("prompt_style") or {}).items()) or \
        "flat 2D stickman cartoon, white round head, black thick outlines"
    lines = ["# Google Flow requests", "",
             "1. Open https://labs.google/flow  2. For each shot below: upload the images from `references/`,",
             "paste the prompt, generate.  3. Download the clip and save it into `inbox/` named exactly as shown.",
             "4. Back in GLAVONJA AI STUDIO press **Continue** - clips are checked and imported automatically.", ""]
    for sc in scenes:
        if not sc.get("use_flow"):
            continue
        name = f"scene_{sc['id']:03d}.mp4"
        lines += [f"## {name}  ({sc['duration']:.1f}s)", "```",
                  FLOW_PROMPT.format(shot=sc.get("description", sc["text"]), style=style_txt,
                                     camera=sc.get("camera", "static"), dur=sc["duration"]).strip(), "```", ""]
    out = folder / "FLOW_REQUESTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def flow_inbox_clip(project, scene_id: int) -> Path | None:
    for ext in (".mp4", ".mov", ".webm"):
        p = project.path("flow", "inbox", f"scene_{scene_id:03d}{ext}")
        if p.exists():
            return p
    return None


# --------------------------------------------------------------------------- approvals
def needs_approval(project, key: str) -> bool:
    return not project.state.setdefault("approvals", {}).get(key, {}).get("approved")


def request_approval(project, key: str, estimate: dict):
    ap = project.state.setdefault("approvals", {})
    if not ap.get(key, {}).get("approved"):
        ap[key] = {"approved": False, "requested": now_iso(), "estimate": estimate}
        project.save()


def approve(project, key: str, approved: bool = True):
    ap = project.state.setdefault("approvals", {})
    ap.setdefault(key, {})
    ap[key].update({"approved": approved, "decided": now_iso(), "declined": not approved})
    project.save()
    get_logger().info("[%s] approval %s -> %s", project.id, key, approved)
