"""Google integration (PART 3.1): Gemini TTS + Google Flow bridge + credit estimates/approvals.

Facts this module is built on (verify yourself, Google changes these often):
  * Gemini TTS is called through the Gemini API (generativelanguage.googleapis.com) with an API key
    from https://aistudio.google.com/apikey .  It returns 24 kHz 16-bit mono PCM.  Free-tier limits
    are small and change; paid use is billed per token.  Numbers live in config/google_pricing.json.
  * Google Flow (labs.google/flow) has NO public API.  We therefore never automate the website.
    The "Flow bridge" prepares exact prompts + reference images, waits for the user's approval,
    and imports the clips the user generated in Flow (drop into the project's flow/inbox folder).
  * Nothing is ever sent to Google without an approval recorded in project_state.json.
"""
